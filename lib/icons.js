/**
 * Badge and link icon markup.
 *
 * Badges resolve from content/badges.json at BUILD time only. The old code
 * consulted localStorage from inside the renderer, so a build run in Node
 * always fell through to a generic placeholder icon — which is why the
 * badges baked into the project cards were "just whatever".
 *
 * A badge entry is `{ name, category, icon?, svg? }`:
 *   icon  path to an image in /assets/icons (preferred — what the tool writes)
 *   svg   inline markup (the built-in set)
 * `icon` wins when both are present.
 */

import { escapeHtml } from './html.js';
import { url } from './paths.js';

export const FALLBACK_BADGE_SVG =
  '<svg viewBox="0 0 24 24" aria-hidden="true" focusable="false"><path d="M9.4 16.6 4.8 12l4.6-4.6L8 6l-6 6 6 6 1.4-1.4zm5.2 0 4.6-4.6-4.6-4.6L16 6l6 6-6 6-1.4-1.4z"/></svg>';

export function normalizeBadgeKey(key) {
  return String(key || '').toLowerCase().replace(/[^a-z0-9]/g, '');
}

export function badgeName(badges, key) {
  const badge = badges[key] || badges[normalizeBadgeKey(key)];
  return badge?.name || key;
}

/** Inner markup for one badge icon (image or inline svg). */
export function badgeIconMarkup(badges, key) {
  const badge = badges[key] || badges[normalizeBadgeKey(key)];
  if (!badge) return FALLBACK_BADGE_SVG;

  if (badge.icon) {
    const name = escapeHtml(badge.name || key);
    return `<img src="${escapeHtml(url(badge.icon))}" alt="${name}" class="tool-badge-img" width="16" height="16" loading="lazy" />`;
  }
  if (badge.svg) return badge.svg;
  return FALLBACK_BADGE_SVG;
}

